def for_language(language):
    """Labels of a language, falling back to English.

    Parameters
    ----------
    language : str
        Language name or code, e.g. ``English``, ``fr``.

    Returns
    -------
    labels : dict
        Fixed wording.
    warning : str or None
        Set when the language has no built-in wording.
    """
    code = LANGUAGES.get(str(language or "english").strip().lower())
    if code:
        return LABELS[code], None
    return LABELS["en"], (f"output.language '{language}': no built-in wording; headings stay in "
                          "English, summaries are written in the requested language")


def fmt_date(day, labels):
    """Long date, e.g. ``16 October 2026``."""
    if isinstance(day, str):
        day = dt.date.fromisoformat(day)
    return labels["date"].format(d=day.day, month=labels["months"][day.month - 1], y=day.year)


def period_phrase(period, labels):
    """Phrase for the covered period, e.g. ``this week``.

    Parameters
    ----------
    period : dict
        ``start``, ``end``, ``unit``, ``length``.
    labels : dict
        Fixed wording.

    Returns
    -------
    str
        Phrase.
    """
    unit, length = period["unit"], period["length"]
    if length == 1:
        return labels["this"][unit].format(end=fmt_date(period["end"], labels))
    return labels["last"][unit].format(n=length)
